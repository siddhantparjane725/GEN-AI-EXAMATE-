
"""Groq LLM integration for MatdarMitra."""

import json
import os
import re
from pathlib import Path

import requests
from dotenv import load_dotenv

BASE_DIR = Path(__file__).resolve().parents[1]

load_dotenv(BASE_DIR / ".env")

PROMPT_DIR = BASE_DIR / "prompts"
GROQ_URL = "https://api.groq.com/openai/v1/chat/completions"


def read_prompt(filename):
    """Read a prompt file from the prompts directory."""
    path = PROMPT_DIR / filename
    return path.read_text(encoding="utf-8")


def safe_response(answer, confidence=0.0, follow_up=""):
    """Return a consistent response structure."""
    try:
        confidence_value = float(confidence)
    except (TypeError, ValueError):
        confidence_value = 0.0

    return {
        "answer": "" if answer is None else str(answer),
        "confidence": max(0.0, min(confidence_value, 1.0)),
        "follow_up": "" if follow_up is None else str(follow_up)
    }


def parse_response(content):
    """Parse and validate the JSON generated by Groq."""
    try:
        if content is None:
            raise ValueError("Missing content")

        if not isinstance(content, str):
            content = json.dumps(content)

        cleaned_content = content.strip()
        fenced_match = re.search(
            r"```(?:json)?\s*(.*?)\s*```",
            cleaned_content,
            flags=re.IGNORECASE | re.DOTALL,
        )
        if fenced_match:
            cleaned_content = fenced_match.group(1)

        data = json.loads(cleaned_content)

        if not isinstance(data, dict):
            raise ValueError("Response is not a JSON object")

        answer = data.get("answer", "")
        confidence = data.get("confidence", 0)
        follow_up = data.get("follow_up", "")

        if not isinstance(answer, str) or not answer.strip():
            raise ValueError("Missing answer")

        return safe_response(answer, confidence, follow_up)

    except (json.JSONDecodeError, TypeError, ValueError):
        return safe_response(
            "I could not generate a reliable response. "
            "Please try asking your question differently.",
            0.0,
            "Would you like to ask about voter registration forms?"
        )


def call_groq(system_prompt, user_prompt):
    """Send prompts to the Groq chat-completions API."""
    api_key = os.getenv("GROQ_API_KEY")
    model = os.getenv("GROQ_MODEL", "openai/gpt-oss-120b")

    if not api_key:
        raise RuntimeError("GROQ_API_KEY is missing from your .env file")

    payload = {
        "model": model,
        "messages": [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt}
        ],
        "temperature": 0.2,
        "max_tokens": 700,
        "response_format": {"type": "json_object"}
    }

    response = requests.post(
        GROQ_URL,
        headers={
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json"
        },
        json=payload,
        timeout=45
    )

    if response.status_code in (400, 422):
        fallback_payload = {key: value for key, value in payload.items() if key != "response_format"}
        response = requests.post(
            GROQ_URL,
            headers={
                "Authorization": f"Bearer {api_key}",
                "Content-Type": "application/json"
            },
            json=fallback_payload,
            timeout=45
        )

    response.raise_for_status()
    result = response.json()

    if not isinstance(result, dict):
        raise RuntimeError("Groq returned an invalid response payload")

    choices = result.get("choices")
    if not isinstance(choices, list) or not choices:
        raise RuntimeError("Groq returned no completion choices")

    message = choices[0].get("message", {})
    content = message.get("content")
    if content is None:
        raise RuntimeError("Groq returned empty content")

    return parse_response(content)


def chat_with_matdarmitra(question, records, prompt_version="1"):
    """Answer a voter question using retrieved ECI records."""

    if prompt_version not in ("1", "2"):
        prompt_version = "1"

    # Retrieve relevant records from the existing TF-IDF search.
    from app.smart_search import smart_search

    matches = smart_search(records, question, limit=5)

    # Ignore very weak search matches.
    matches = [
        item for item in matches
        if isinstance(item, dict)
        and float(item.get("similarity_score", 0) or 0) >= 0.05
    ]

    # Do not ask the LLM to invent an answer without source material.
    if not matches:
        return safe_response(
            "I could not find relevant information in the available "
            "Election Commission of India records. Please check the "
            "official ECI website or contact your election office.",
            0.0,
            "Would you like help with Form 6, Form 7, or Form 8?"
        )

    system_prompt = read_prompt("system.txt")
    task_prompt = read_prompt(f"task_prompt_{prompt_version}.txt")

    context = json.dumps(matches, ensure_ascii=False, indent=2)

    user_prompt = f"""
TASK INSTRUCTIONS:
{task_prompt}

USER QUESTION:
{question}

RETRIEVED ECI RECORDS:
{context}

Answer using only the retrieved records.
Return valid JSON with exactly these fields:
{{
  "answer": "Your answer",
  "confidence": 0.0,
  "follow_up": "One useful follow-up question"
}}
"""

    return call_groq(system_prompt, user_prompt)
